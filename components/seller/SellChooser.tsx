type Props = {
  open: boolean;
  onClose: () => void;
  onChoose: (mode: SellMode) => void;
};

export default function SellChooser({ open, onClose, onChoose }: Props) {
  // Portals need document, which does not exist during server rendering.
  const [mounted, setMounted] = useState(false);
  const optionsRef = useRef<HTMLDivElement>(null);
  useEffect(() => setMounted(true), []);

  useEffect(() => {
    if (!open) return;
    // Focus goes to the first choice, and back to whatever opened this (Sell,
    // or the menu row) when it closes, so a keyboard never loses its place.
    const previouslyFocused = document.activeElement as HTMLElement | null;
    optionsRef.current?.querySelector("button")?.focus({ preventScroll: true });
    const originalOverflow = document.body.style.overflow;
    document.body.style.overflow = "hidden";
    const onKeyDown = (event: KeyboardEvent) => {
      if (event.key === "Escape") onClose();
    };
    document.addEventListener("keydown", onKeyDown);
    return () => {
      document.removeEventListener("keydown", onKeyDown);
      document.body.style.overflow = originalOverflow;
      previouslyFocused?.focus({ preventScroll: true });
    };
  }, [open, onClose]);

  if (!mounted) return null;

  // Always rendered once mounted, so closing can animate out. `inert` keeps
  // the closed layer out of reach of taps, tabbing and screen readers.
  return createPortal(
    <div
      className={open ? "sell-chooser is-open" : "sell-chooser"}
      role="dialog"
      aria-modal="true"
      aria-label="What are you selling?"
      inert={!open}
    >
      <div className="sell-chooser-scrim" onClick={onClose} aria-hidden="true" />
      <div className="sell-chooser-options" ref={optionsRef}>
        <SecondaryButton className="sell-chooser-option" onClick={() => onChoose("single")}>
          <OneItemIcon />
          One item
        </SecondaryButton>
        <SecondaryButton className="sell-chooser-option" onClick={() => onChoose("bulk")}>
          <ManyItemsIcon />
          Many items
        </SecondaryButton>
      </div>
      <button type="button" className="fab sell-chooser-close" onClick={onClose} aria-label="Close">
        <CloseIcon />
      </button>
    </div>,
    document.body,
  );
}
